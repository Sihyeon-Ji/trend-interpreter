  ko: { emerging: "새로 퍼지는 중", rising: "늘어나는 중", peak: "정점", steady: "꾸준함", declining: "줄어드는 중", dormant: "거의 안 쓰임", unknown: "추세 미확인" },
  en: { emerging: "Emerging", rising: "Rising", peak: "Peaking", steady: "Steady", declining: "Declining", dormant: "Dormant", unknown: "Unclear" },
