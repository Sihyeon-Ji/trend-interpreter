const COPY: Record<Locale, Copy> = { ko, en };
export type CopyKey = keyof typeof ko;

/** 문구 하나. {name} 자리를 채운다 */
export function tr(locale: Locale, key: CopyKey, vars: Record<string, string | number> = {}): string {
  return COPY[locale][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

