const COPY: Record<Locale, Copy> = { ko, en };

/** 문구 하나. {name} 자리는 vars 로 채운다. */
export function fe(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  let s = COPY[locale].s[key] ?? COPY.ko.s[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
export const words = (locale: Locale) => COPY[locale];
