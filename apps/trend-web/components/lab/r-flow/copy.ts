const COPY: Record<Locale, Copy> = { ko, en };

/** 화면 문구. {name} 자리를 값으로 채운다 */
export function tr(locale: Locale, key: CopyKey, vars?: Record<string, string | number>): string {
  const s = COPY[locale][key];
  if (!vars) return s;
  return Object.entries(vars).reduce((acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)), s);
}

export const MARKETS = ["KR", "JP", "GLOBAL"] as const;
export type Market = (typeof MARKETS)[number];
export const isMarket = (m: unknown): m is Market => MARKETS.includes(m as Market);
export const marketName = (locale: Locale, m: string) => (isMarket(m) ? tr(locale, `market_${m}`) : m);
export const MARKET_LANG: Record<Market, "ko" | "ja" | "en"> = { KR: "ko", JP: "ja", GLOBAL: "en" };

/** 숫자는 화면 언어와 상관없이 1,234 꼴 */
export const num = (n: number) => n.toLocaleString("en-US");
