const DICT: Record<Locale, Record<Key, string>> = { ko, en, ja };
export type CopyKey = Key;

/** 화면 문구 하나. {name} 자리에 값을 끼운다 */
export function tx(locale: Locale, key: Key, vars?: Record<string, string | number>): string {
  const s = DICT[locale][key];
  if (!vars) return s;
  return Object.entries(vars).reduce((acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)), s);
}

export const MARKETS = ["KR", "JP", "GLOBAL"] as const;
export type Market = (typeof MARKETS)[number];
export const MARKET_LANG: Record<Market, "ko" | "ja" | "en"> = { KR: "ko", JP: "ja", GLOBAL: "en" };
export const isMarket = (s: string | null | undefined): s is Market => !!s && (MARKETS as readonly string[]).includes(s);
export const marketName = (locale: Locale, m: string) => (isMarket(m) ? tx(locale, `m_${m}` as Key) : m);

